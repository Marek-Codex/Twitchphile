// Inlines the Phosphor icons we use (MIT, phosphoricons.com) into src/ui/icons.ts.
// Usage: node scripts/icons.mjs — edit ICONS to add more.
import { readFileSync, writeFileSync } from "node:fs";

const WEIGHT = "bold";
const ICONS = {
  // stats strip
  gauge: "gauge",
  clock: "clock",
  trendUp: "trend-up",
  trendDown: "trend-down",
  trendFlat: "arrow-right",
  hourglass: "hourglass-medium",
  // player bar, chat, sidebar
  camera: "camera",
  cinema: "frame-corners",
  pip: "picture-in-picture",
  download: "download-simple",
  copy: "copy",
  at: "at",
  star: "star",
  tag: "tag",
  // settings button, panel, popup
  settings: "sliders-horizontal",
  search: "magnifying-glass",
  close: "x",
  refresh: "arrow-clockwise",
  hide: "eye-slash",
  users: "users",
  // panel categories
  player: "play-circle",
  stream: "chart-line",
  chat: "chat-circle",
  filters: "funnel",
  live: "broadcast",
  autoOpen: "arrow-square-out",
  declutter: "broom",
  data: "database",
  points: "coins",
};

// One export per icon so each bundle only includes the icons it actually imports.
const out = Object.entries(ICONS).map(([name, file]) => {
  const svg = readFileSync(`node_modules/@phosphor-icons/core/assets/${WEIGHT}/${file}-${WEIGHT}.svg`, "utf8");
  const inner = svg.replace(/^<svg[^>]*>|<\/svg>\s*$/g, "");
  return `export const ${name} = ${JSON.stringify(inner)};`;
});

writeFileSync(
  "src/ui/icons.ts",
  `// Generated by scripts/icons.mjs from Phosphor Icons (${WEIGHT}, MIT). Do not edit by hand.
// Usage: svg(camera, 20). Each icon is its own export so unused ones are tree-shaken away.

export const svg = (icon: string, size = 14) =>
  \`<svg class="tp-i" width="\${size}" height="\${size}" viewBox="0 0 256 256" fill="currentColor" aria-hidden="true">\${icon}</svg>\`;

${out.join("\n")}
`,
);
console.log(`wrote ${out.length} icons`);
